// Standard glTF-Transform display LOD. Keep the exact source asset separately.
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS, EXTMeshoptCompression } from '@gltf-transform/extensions';
import { quantize, simplify, weld, reorder } from '@gltf-transform/functions';
import { MeshoptDecoder, MeshoptEncoder, MeshoptSimplifier } from 'meshoptimizer';
import { readFile, writeFile, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';

await Promise.all([MeshoptDecoder.ready, MeshoptEncoder.ready, MeshoptSimplifier.ready]);
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.decoder': MeshoptDecoder, 'meshopt.encoder': MeshoptEncoder });
const input = 'assets/actuator.meshopt.glb', output = 'assets/actuator.web.glb';
const document = await io.read(input);

function capture(doc) {
  const parts = [];
  for (const node of doc.getRoot().listNodes()) {
    const mesh = node.getMesh();
    if (!mesh) continue;
    const matrix = node.getWorldMatrix();
    for (const primitive of mesh.listPrimitives()) {
      const accessor = primitive.getAttribute('POSITION');
      const points = new Float64Array(accessor.getCount() * 3), position = [];
      for (let i = 0; i < accessor.getCount(); i++) {
        accessor.getElement(i, position);
        for (let axis = 0; axis < 3; axis++) points[i * 3 + axis] = matrix[axis] * position[0] + matrix[4 + axis] * position[1] + matrix[8 + axis] * position[2] + matrix[12 + axis];
      }
      parts.push({ name: node.getName(), points, indices: primitive.getIndices()?.getArray().slice() });
    }
  }
  return parts;
}

const original = capture(document);
await document.transform(
  weld(),
  simplify({ simplifier: MeshoptSimplifier, ratio: .18, error: .0003, lockBorder: false }),
  reorder({ encoder: MeshoptEncoder, target: 'performance' }),
);
const before = capture(document);
if (original.length !== before.length || original.some((part, index) => part.name !== before[index].name)) throw new Error('A source part was removed');
for (const node of document.getRoot().listNodes()) {
  if (node.getMesh()) node.setExtras({ ...node.getExtras(), presentationY: node.getTranslation()[1] });
}
await document.transform(quantize({ quantizePosition: 16, quantizeNormal: 12, cleanup: false }));
document.createExtension(EXTMeshoptCompression).setRequired(true).setEncoderOptions({ method: EXTMeshoptCompression.EncoderMethod.QUANTIZE });
await io.write(output, document);
const after = capture(await io.read(output));
if (before.length !== after.length) throw new Error('Source mesh count changed');
let maximumPositionError = 0, vertices = 0, triangles = 0;
before.forEach((part, index) => {
  const next = after[index];
  if (part.name !== next.name || part.points.length !== next.points.length || part.indices?.length !== next.indices?.length) throw new Error(`Source part changed: ${part.name}`);
  // Meshopt's triangle encoding may cyclically rotate indices. Orientation and
  // triangle membership must still match after quantization/compression.
  for (let i = 0; i < part.indices.length; i += 3) {
    const offset = [0, 1, 2].find(offset => part.indices[i] === next.indices[i + offset]);
    if (offset === undefined || part.indices[i + 1] !== next.indices[i + (offset + 1) % 3] || part.indices[i + 2] !== next.indices[i + (offset + 2) % 3]) throw new Error(`LOD topology changed during compression: ${part.name}`);
  }
  for (let i = 0; i < part.points.length; i += 3) maximumPositionError = Math.max(maximumPositionError, Math.hypot(part.points[i] - next.points[i], part.points[i + 1] - next.points[i + 1], part.points[i + 2] - next.points[i + 2]));
  vertices += part.points.length / 3;
  triangles += part.indices.length / 3;
});
if (maximumPositionError > .01) throw new Error(`Position error exceeds 0.01 source millimeters: ${maximumPositionError}`);
const manifestFile = 'assets/source-manifest.json';
const manifest = JSON.parse(await readFile(manifestFile, 'utf8'));
manifest.webModel = {
  file: 'actuator.web.glb', source: manifest.model.file, bytes: (await stat(output)).size,
  sha256: createHash('sha256').update(await readFile(output)).digest('hex'),
  transform: '@gltf-transform/functions@4.5.1 weld, simplify, reorder, quantize + EXT_meshopt_compression; position 16-bit, normal 12-bit',
  sourceMeshes: original.length, renderedMeshes: after.length, sourceTriangles: original.reduce((total, part) => total + part.indices.length / 3, 0), renderedVertices: vertices, renderedTriangles: triangles,
  quantizedTopologyVerified: true, maximumQuantizationWorldPositionErrorMillimeters: maximumPositionError,
  simplification: { requestedTriangleRatio: .18, maximumRelativeError: .0003, topologicalBordersLocked: false, note: 'Display LOD generated by meshoptimizer at 0.03% relative error; the 69 source parts, their placement and materials are retained. The original exact source model remains available unchanged.' },
  reproducibleWith: 'node optimize-model.mjs',
};
await writeFile(manifestFile, JSON.stringify(manifest, null, 2) + '\n');
console.log(JSON.stringify(manifest.webModel, null, 2));
