import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { graphDomain, inspectionYears } from './graph-data.js';

const root = new URL('./', import.meta.url);
const series = ['llm', 'humanoid', 'specialist', 'deployment', 'data', 'hardware'];
const files = ['graph-history-language-hardware.json', 'graph-history-robotics.json', 'graph-future-stories.json'];
const stories = (await Promise.all(files.map(async file => JSON.parse(await readFile(new URL(file, root), 'utf8'))))).flat();
const byId = new Map();
const missingArtwork = [];
const artworkPlaceholders = [];
const artworkHashes = new Map();
for (const story of stories) {
  if (!series.includes(story.seriesId) || !Number.isInteger(story.year) || story.year < 2015 || story.year > 2040) throw new Error(`Invalid story identity: ${story.id}`);
  if (story.id !== `${story.seriesId}-${story.year}` || byId.has(story.id)) throw new Error(`Duplicate or invalid story: ${story.id}`);
  if (story.kind !== (story.year <= 2026 ? 'history' : 'scenario')) throw new Error(`Wrong era: ${story.id}`);
  if (!story.title || !story.blurb || !story.sourceUrl || !story.media) throw new Error(`Incomplete story: ${story.id}`);
  const wordCount = story.blurb.trim().split(/\s+/u).length;
  if (wordCount < 25 || wordCount > 45) throw new Error(`Story blurb must be 25–45 words: ${story.id} (${wordCount})`);
  if (new URL(story.sourceUrl).protocol !== 'https:') throw new Error(`Source must use HTTPS: ${story.id}`);
  const allowed = story.kind === 'scenario' ? ['image'] : ['youtube', 'native', 'slideslive', 'wistia'];
  if (!allowed.includes(story.media.provider)) throw new Error(`Unexpected media provider: ${story.id}`);
  if (['native', 'image'].includes(story.media.provider) ? !story.media.src : !story.media.id) throw new Error(`Missing media reference: ${story.id}`);
  if (story.kind === 'scenario') {
    if (story.media.src !== `graph-media/future/${story.seriesId}/${story.year}.webp`) throw new Error(`Unexpected sketch path: ${story.id}`);
    if (story.media.state !== undefined && !['placeholder', 'ready'].includes(story.media.state)) throw new Error(`Invalid sketch state: ${story.id}`);
    if (story.media.state === 'placeholder') artworkPlaceholders.push(story.id);
    let bytes;
    try { bytes = await readFile(new URL(story.media.src, root)); } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      missingArtwork.push(story.id);
      if (story.media.state !== 'placeholder') throw new Error(`Missing artwork must be explicitly marked as a placeholder: ${story.id}`);
    }
    if (bytes) {
      if (bytes.length < 1024 || bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WEBP') throw new Error(`Invalid WebP artwork: ${story.id}`);
      const hash = createHash('sha256').update(bytes).digest('hex');
      if (artworkHashes.has(hash)) throw new Error(`Sketch reused for two states: ${artworkHashes.get(hash)} and ${story.id}`);
      artworkHashes.set(hash, story.id);
    }
  }
  byId.set(story.id, story);
}
for (const id of series) for (let year = 2015; year <= 2040; year++) if (!byId.has(`${id}-${year}`)) throw new Error(`Missing story: ${id}-${year}`);
if (stories.length !== 156) throw new Error(`Expected 156 stories, got ${stories.length}`);
const requiredArtwork = stories.filter(story => story.year > graphDomain.dividerYear && inspectionYears.includes(story.year));
const unfinishedArtwork = new Set([...missingArtwork, ...artworkPlaceholders]);
const missingMilestones = requiredArtwork.filter(story => unfinishedArtwork.has(story.id)).map(story => story.id);
if (process.argv.includes('--require-art') && missingMilestones.length) throw new Error(`Recraft milestone artwork not complete: ${missingMilestones.join(', ')}`);
const runtime = stories.sort((a, b) => a.year - b.year || series.indexOf(a.seriesId) - series.indexOf(b.seriesId)).map(({ sketchPrompt, sketchBrief, ...story }) => story);
const output = `// Generated by build-stories.mjs from the checked-in research and scenario manifests.\nexport const graphStories = Object.freeze(${JSON.stringify(runtime)});\nconst storiesById = new Map(graphStories.map(story => [story.id, story]));\nexport function getStory(seriesId, year) { return storiesById.get(seriesId + '-' + year) ?? null; }\nexport const storyCoverage = Object.freeze({ historical: 72, future: 84, total: 156 });\n`;
await writeFile(new URL('graph-stories.js', root), output, 'utf8');
console.log(JSON.stringify({ records: runtime.length, historical: 72, future: 84, artworkPresent: 84 - missingArtwork.length, artworkPlaceholders: artworkPlaceholders.length, requiredArtwork: requiredArtwork.length, requiredArtworkReady: requiredArtwork.length - missingMilestones.length, publishable: true, output: fileURLToPath(new URL('graph-stories.js', root)) }));
